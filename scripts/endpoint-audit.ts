// Writes docs/ENDPOINT-AUDIT.md: every subscribed DATEV product, its operations, and what the offline eval and live sweep proved.
// Lists operation ids and counts only, never DATEV's own descriptions (their terms forbid redistributing API docs).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { OPERATIONS } from "../src/tools/catalog.js";

interface Entry { op: string; status: number | "skipped" | "error"; ts: string; note?: string }
const ledgerPath = "test/reports/live-ledger.jsonl";
const latest = new Map<string, Entry>();
if (existsSync(ledgerPath)) for (const l of readFileSync(ledgerPath, "utf8").split("\n").filter(Boolean)) {
  const e = JSON.parse(l) as Entry;
  latest.set(e.op, e);
}
const evalFile = existsSync("test/reports") ? readdirSync("test/reports").filter((f) => /^eval-.*\.json$/.test(f)).sort().pop() : undefined;
const evalSummary = evalFile ? (JSON.parse(readFileSync(`test/reports/${evalFile}`, "utf8")) as { total: number; passed: number; failed: number; generatedAt: string; failures: { op: string }[] }) : undefined;
const evalFailedOps = new Set(evalSummary?.failures.map((f) => f.op) ?? []);

const live = (id: string) => {
  const e = latest.get(id);
  if (!e) return "not run";
  if (e.status === "skipped") return `skipped: ${e.note ?? ""}`;
  if (e.status === "error") return "local error";
  return e.status < 300 ? `${e.status} ok` : String(e.status);
};

const products = [...new Set(OPERATIONS.map((o) => o.product))].sort();
const summaryRows = products.map((p) => {
  const ops = OPERATIONS.filter((o) => o.product === p);
  const reads = ops.filter((o) => o.method === "get");
  const ok = reads.filter((o) => {
    const e = latest.get(o.id);
    return e && typeof e.status === "number" && e.status < 300;
  }).length;
  const reached = reads.filter((o) => {
    const e = latest.get(o.id);
    return e && typeof e.status === "number";
  }).length;
  return `| ${p} | ${ops.length} | ${reads.length} | ${ops.length - reads.length} | ${ops.every((o) => o.servers.sandbox) ? "yes" : ops.some((o) => o.servers.sandbox) ? "partly" : "no"} | ${ops.some((o) => evalFailedOps.has(o.id)) ? "FAIL" : "pass"} | ${reached}/${reads.length} | ${ok} |`;
});

const detail = products.flatMap((p) => [
  "",
  `### ${p}`,
  "",
  "| Operation id | Method | Writes data | Offline eval | Live sandbox |",
  "|---|---|---|---|---|",
  ...OPERATIONS.filter((o) => o.product === p).map((o) => `| \`${o.id}\` | ${o.method.toUpperCase()} | ${o.write ? "yes, preview first" : "no"} | ${evalFailedOps.has(o.id) ? "FAIL" : "pass"} | ${o.method === "get" ? live(o.id).replace(/\|/g, "/") : "not swept (changes data)"} |`),
]);

const md = [
  "<!-- freshness: 14d -->",
  "# Endpoint audit",
  "",
  "This page is generated by `npx tsx scripts/endpoint-audit.ts` from the operation index and the live call ledger. Do not edit it by hand.",
  "",
  "It lists operation ids and counts only. DATEV's own descriptions stay out, because DATEV's terms of use do not allow passing their API documentation on.",
  "",
  `- Products: ${products.length}. Operations: ${OPERATIONS.length}, of which ${OPERATIONS.filter((o) => o.method === "get").length} read and ${OPERATIONS.filter((o) => o.method !== "get").length} change data.`,
  evalSummary ? `- Offline eval (${evalSummary.generatedAt}): ${evalSummary.passed} of ${evalSummary.total} scenarios passed, ${evalSummary.failed} failed.` : "- Offline eval: not run yet (`npm run eval`).",
  `- Live sandbox: ${[...latest.values()].filter((e) => typeof e.status === "number").length} read operations reached DATEV. Write operations are never swept live, because they change data.`,
  "",
  "## By product",
  "",
  "| Product | Operations | Read | Change data | Sandbox server | Offline eval | Live reached | Live 2xx |",
  "|---|---|---|---|---|---|---|---|",
  ...summaryRows,
  "",
  "A live result other than 2xx is not a defect by itself. 401 and 403 mean the sandbox app is not permitted for that resource, 404 means the test data has no such record. The verdict per operation is in the tables below.",
  "",
  "## Every operation",
  ...detail,
  "",
].join("\n");
writeFileSync("docs/ENDPOINT-AUDIT.md", md);
console.log(`docs/ENDPOINT-AUDIT.md: ${products.length} products, ${OPERATIONS.length} operations`);
